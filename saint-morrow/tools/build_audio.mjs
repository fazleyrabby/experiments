// Downloads public-domain recordings from Wikimedia Commons and embeds them as base64 AAC.
// Usage: node saint-morrow/tools/build_audio.mjs <download-cache-dir>
import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';

const run = promisify(execFile);
const SOURCES = [
  {
    key: 'rain',
    title: 'Rain.ogg',
    url: 'https://upload.wikimedia.org/wikipedia/commons/3/3d/Rain.ogg',
    sha1: 'd9ad5297c79e6ac2acc9ccd7181c4b144798c306',
    author: 'ジダネ',
    bitrate: '128k',
  },
  {
    key: 'thunder',
    title: 'Rain and thunder.ogg',
    url: 'https://upload.wikimedia.org/wikipedia/commons/4/42/Rain_and_thunder.ogg',
    sha1: '5cee3290a09118a6d2fcdcbaa17f451f9ec09499',
    author: 'User:Caesar',
    bitrate: '96k',
  },
];

const cache = process.argv[2];
if (!cache) throw new Error('Pass a download cache directory.');
await mkdir(cache, { recursive: true });
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = path.join(root, 'js', 'audio');
await mkdir(outDir, { recursive: true });

const embedded = {};
for (const source of SOURCES) {
  const response = await fetch(source.url, { headers: { 'User-Agent': 'saint-morrow-asset-tool/1.0' } });
  if (!response.ok) throw new Error(`${response.status} for ${source.url}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  if (createHash('sha1').update(bytes).digest('hex') !== source.sha1) throw new Error(`Checksum mismatch: ${source.title}`);

  const input = path.join(cache, `${source.key}.ogg`);
  const output = path.join(cache, `${source.key}.m4a`);
  await writeFile(input, bytes);
  await run('ffmpeg', ['-y', '-v', 'error', '-i', input, '-vn', '-af', 'loudnorm=I=-20:TP=-2:LRA=11', '-ar', '44100', '-c:a', 'aac', '-b:a', source.bitrate, '-movflags', '+faststart', output]);
  embedded[source.key] = `data:audio/mp4;base64,${(await readFile(output)).toString('base64')}`;
  console.log(`${source.key}: ${(embedded[source.key].length / 1024).toFixed(0)} KB embedded`);
}

await writeFile(path.join(outDir, 'recordings.js'), `// Generated by tools/build_audio.mjs. Public-domain recordings, see CREDITS.md.\nexport const RECORDINGS = ${JSON.stringify(embedded)};\n`);
await writeFile(path.join(outDir, 'CREDITS.md'), `# Audio credits\n\nPublic-domain recordings from Wikimedia Commons, loudness-normalized and re-encoded.\n\n${SOURCES.map((s) => `- ${s.title} by ${s.author}: https://commons.wikimedia.org/wiki/File:${encodeURIComponent(s.title.replaceAll(' ', '_'))}`).join('\n')}\n`);
