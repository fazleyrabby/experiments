import * as THREE from 'three';
import { OrbitControls } from 'three/addons/controls/OrbitControls.js';
import { RoomEnvironment } from 'three/addons/environments/RoomEnvironment.js';

export function createStudio(container, reducedMotion) {
  const scene = new THREE.Scene();
  scene.fog = new THREE.FogExp2('#14191d', .014);
  const renderer = new THREE.WebGLRenderer({ antialias: true, alpha: true, powerPreference: 'high-performance' });
  renderer.setPixelRatio(Math.min(window.devicePixelRatio, 1.75));
  renderer.outputColorSpace = THREE.SRGBColorSpace;
  renderer.toneMapping = THREE.ACESFilmicToneMapping;
  renderer.toneMappingExposure = 1.28;
  renderer.shadowMap.enabled = true;
  renderer.shadowMap.type = THREE.PCFSoftShadowMap;
  container.appendChild(renderer.domElement);
  renderer.domElement.setAttribute('aria-label', 'Procedural V8 engine. Drag to rotate and pinch or scroll to zoom.');
  const camera = new THREE.PerspectiveCamera(33, 1, .1, 150);
  const controls = new OrbitControls(camera, renderer.domElement);
  controls.enableDamping = true;
  controls.dampingFactor = .07;
  controls.enablePan = false;
  controls.minDistance = 12;
  controls.maxDistance = 55;
  controls.minPolarAngle = .18;
  controls.maxPolarAngle = Math.PI * .78;
  controls.rotateSpeed = .65;
  controls.zoomSpeed = .7;

  // The environment is generated by Three.js geometry, with no downloaded HDRI.
  const room = new RoomEnvironment();
  const pmrem = new THREE.PMREMGenerator(renderer);
  const environment = pmrem.fromScene(room, .04);
  scene.environment = environment.texture;
  scene.environmentIntensity = .65;
  room.dispose(); pmrem.dispose();

  const hemi = new THREE.HemisphereLight('#becdd5', '#15151b', 1.0); scene.add(hemi);
  const light = (color, intensity, position) => {
    const result = new THREE.DirectionalLight(color, intensity); result.position.set(...position); scene.add(result); return result;
  };
  const key = light('#eef4ff', 4.5, [-5, 9, 7]);
  key.castShadow = true; key.shadow.mapSize.set(1024, 1024);
  Object.assign(key.shadow.camera, { left: -11, right: 11, top: 12, bottom: -12, near: .5, far: 40 });
  key.shadow.bias = -.0006; key.shadow.normalBias = .04;
  light('#b6c9de', 3.4, [5, 5, -8]);
  light('#efb485', 1.5, [-7, 1, -2]);
  light('#d8e5eb', 1.25, [5, 2, 9]);
  const floor = new THREE.Mesh(new THREE.PlaneGeometry(200, 200), new THREE.ShadowMaterial({ color: '#000000', opacity: .2 }));
  floor.rotation.x = -Math.PI / 2; floor.position.y = -4.3; floor.receiveShadow = true; scene.add(floor);

  // A very quiet engineering datum, with no particles or stars.
  const datum = new THREE.Group();
  const lineMaterial = new THREE.LineBasicMaterial({ color: '#627279', transparent: true, opacity: .14 });
  const circleGeometry = new THREE.BufferGeometry().setFromPoints(Array.from({ length: 129 }, (_, i) => {
    const a = i / 128 * Math.PI * 2; return new THREE.Vector3(Math.cos(a) * 4.9, 0, Math.sin(a) * 4.9);
  }));
  datum.add(new THREE.Line(circleGeometry, lineMaterial));
  for (let i = 0; i < 48; i++) {
    const a = i / 48 * Math.PI * 2;
    const inner = i % 4 === 0 ? 5.04 : 5.13;
    const g = new THREE.BufferGeometry().setFromPoints([new THREE.Vector3(Math.cos(a) * inner, 0, Math.sin(a) * inner), new THREE.Vector3(Math.cos(a) * 5.25, 0, Math.sin(a) * 5.25)]);
    datum.add(new THREE.Line(g, lineMaterial));
  }
  datum.position.y = -2.25; scene.add(datum);

  let width = 1, height = 1, mobile = false;
  let interaction = false, framing = true, reset = false, zoomFactor = 1;
  let lastBaseDistance = 25;
  const cameraDirection = new THREE.Vector3(1.05, .73, 1.32).normalize();
  const idealPosition = new THREE.Vector3();
  const idealTarget = new THREE.Vector3();
  function resize() {
    const rect = container.getBoundingClientRect();
    width = rect.width; height = rect.height; mobile = width <= 800;
    renderer.setSize(width, height);
    camera.aspect = width / height;
    // Offset projection to preserve space for the editorial UI.
    camera.setViewOffset(width, height, 0, -height * .025, width, height);
    camera.updateProjectionMatrix();
    framing = true;
  }
  function baseDistance(progress) {
    if (mobile) return THREE.MathUtils.lerp(22, 32, progress) * Math.max(1, .86 / camera.aspect);
    return THREE.MathUtils.lerp(21, 29.5, progress) * Math.max(1, 1.45 / camera.aspect);
  }
  function resetView() { reset = true; framing = true; zoomFactor = 1; }
  function startInteraction() { interaction = true; reset = false; framing = false; }
  function endInteraction() { interaction = false; zoomFactor = Math.max(.5, Math.min(1.6, camera.position.distanceTo(controls.target) / lastBaseDistance)); }
  controls.addEventListener('start', startInteraction); controls.addEventListener('end', endInteraction);
  resize();
  controls.target.set(0, .8, 0);
  camera.position.copy(cameraDirection).multiplyScalar(baseDistance(0)).add(controls.target);
  controls.update();
  const resizeObserver = new ResizeObserver(resize); resizeObserver.observe(container);

  function update(dt, progress) {
    const distance = baseDistance(progress);
    if (reset) {
      idealTarget.set(0, .8 + progress * .42, 0);
      idealPosition.copy(cameraDirection).multiplyScalar(distance).add(idealTarget);
      const t = reducedMotion ? 1 : 1 - Math.exp(-dt * 4);
      controls.target.lerp(idealTarget, t); camera.position.lerp(idealPosition, t);
      if (camera.position.distanceTo(idealPosition) < .02) { reset = false; framing = false; }
    } else if (!interaction) {
      // Preserve user orbit and zoom, while widening smoothly with disassembly.
      const desiredDistance = distance * zoomFactor;
      idealPosition.copy(camera.position).sub(controls.target).normalize().multiplyScalar(desiredDistance).add(controls.target);
      camera.position.lerp(idealPosition, 1 - Math.exp(-dt * 2.6));
      if (framing) framing = false;
    }
    lastBaseDistance = distance;
    datum.visible = progress < .7;
    lineMaterial.opacity = .14 * (1 - progress);
    controls.update(dt);
  }
  return { scene, camera, renderer, controls, update, resetView, get interacting() { return interaction; },
    dispose() {
      resizeObserver.disconnect(); controls.dispose(); renderer.setAnimationLoop(null);
      environment.dispose(); floor.geometry.dispose(); floor.material.dispose();
      datum.traverse(o => o.geometry?.dispose()); lineMaterial.dispose();
      key.shadow.map?.dispose(); renderer.dispose(); renderer.domElement.remove();
    },
  };
}
